function inPolygon(lon: number, lat: number, poly: Polygon): boolean {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

export function isLand(lon: number, lat: number): boolean {
  return CONTINENTS.some((p) => inPolygon(lon, lat, p));
}

/** 地図の表示範囲（南極は省略） */
export const MAP_LAT_TOP = 80;
export const MAP_LAT_BOTTOM = -58;

let cache: { cols: number; rows: number; dots: { lon: number; lat: number }[] } | null = null;

/** 指定の解像度で陸地のドット座標を返す（結果はキャッシュ） */
export function landDots(cols: number, rows: number): { lon: number; lat: number }[] {
  if (cache && cache.cols === cols && cache.rows === rows) return cache.dots;
  const dots: { lon: number; lat: number }[] = [];
  for (let r = 0; r < rows; r++) {
    const lat = MAP_LAT_TOP - ((r + 0.5) / rows) * (MAP_LAT_TOP - MAP_LAT_BOTTOM);
    for (let c = 0; c < cols; c++) {
      const lon = -180 + ((c + 0.5) / cols) * 360;
      if (isLand(lon, lat)) dots.push({ lon, lat });
    }
  }
  cache = { cols, rows, dots };
  return dots;
}
